	<!-- wp:heading -->
	<h2 class="wp-block-heading">Rechtmatige grondslag</h2>
	<!-- /wp:heading -->

	<!-- wp:paragraph -->
	<p>De vereniging verwerkt alleen persoonsgegevens als daarvoor een van de volgende grondslagen van toepassing is (artikel 6 AVG): om een wettelijke verplichting na te komen; voor de uitvoering van een overeenkomst waarvan de betrokkene onderdeel was; om een ernstige bedreiging voor de gezondheid van de betrokkene te bestrijden; voor de goede vervulling van de taak van de vereniging; of wanneer de betrokkene toestemming heeft gegeven voor een specifieke verwerking. Dat laatste is doorgaans het geval, maar als bijvoorbeeld iemand tijdens een evenement medische hulp nodig heeft, kan het nodig zijn persoonsgegevens te verstrekken.</p>
	<!-- /wp:paragraph -->

	<!-- wp:heading -->
	<h2 class="wp-block-heading">Wijze van verwerking</h2>
	<!-- /wp:heading -->

	<!-- wp:paragraph -->
	<p>De verwerking van persoonsgegevens is alleen toegestaan als dit in overeenstemming is met de wet en op een zorgvuldige wijze gebeurt. Persoonsgegevens worden uitsluitend verkregen van de betrokkene zelf, die voorafgaand aan de eerste verwerking op de hoogte wordt gesteld van die verwerking en van het bestaan en de opvraagbaarheid van de geldende regels. Het nieuwe lid verleent vooraf, vrijelijk, specifiek, geïnformeerd en ondubbelzinnig toestemming voor de verwerking. Persoonsgegevens worden slechts verwerkt voor zover zij, gelet op de doeleinden, toereikend, ter zake dienend en niet bovenmatig zijn. Gegevens over deelnemers aan activiteiten worden niet langer bewaard dan nodig voor die activiteit.</p>
	<!-- /wp:paragraph -->

	<!-- wp:heading -->
	<h2 class="wp-block-heading">Persoonsgegevens</h2>
	<!-- /wp:heading -->

	<!-- wp:paragraph -->
	<p>De vereniging verwerkt slechts gegevens van leden en van personen met wie zij een zakelijke (vrijwilligers) of financiële (sponsoren) relatie onderhoudt. Leden worden geregistreerd via de ledenadministratie; vrijwilligers en sponsoren via het secretariaat. Bij inschrijving worden de volgende verplichte gegevens ingevuld: voornaam, achternaam, adres, postcode, woonplaats, geboortedatum, geslacht, telefoonnummer, e-mailadres, ingangsdatum lidmaatschap, eigen of geleend instrument en machtigingsgegevens (banknummer). Daaraan worden de datum en tijd van registratie toegevoegd.</p>
	<!-- /wp:paragraph -->

	<!-- wp:paragraph -->
	<p>De gegevens worden niet langer bewaard dan noodzakelijk, tenzij ze nodig zijn om te voldoen aan een wettelijke bewaarplicht. Verwijderde gegevens worden vernietigd, tenzij ze nodig zijn voor historisch onderzoek of archivering; in dat geval worden passende maatregelen getroffen zodat de gegevens uitsluitend geanonimiseerd en voor dat doel worden gebruikt.</p>
	<!-- /wp:paragraph -->

	<!-- wp:heading -->
	<h2 class="wp-block-heading">Toegang tot en verstrekking van persoonsgegevens</h2>
	<!-- /wp:heading -->

	<!-- wp:paragraph -->
	<p>Muziekvereniging Soli verstrekt nooit persoonsgegevens aan derden. Afhankelijk van toegekende permissies hebben leden van de organisatie mogelijk toegang tot persoonsgegevens van deelnemers; zij zijn verplicht tot geheimhouding van de gegevens waarvan zij kennisnemen. Persoonsgegevens worden uitsluitend verstrekt aan leden van de organisatie, in het kader van de activiteiten en in overeenstemming met de genoemde doeleinden.</p>
	<!-- /wp:paragraph -->

	<!-- wp:heading -->
	<h2 class="wp-block-heading">Beveiliging</h2>
	<!-- /wp:heading -->

	<!-- wp:paragraph -->
	<p>De vereniging draagt zorg voor de nodige voorzieningen van fysieke, technische en organisatorische aard ter beveiliging van de persoonsgegevens die zijn opgeslagen in de administratie, bij het secretariaat en op de website, tegen verlies of enige vorm van onrechtmatige verwerking.</p>
