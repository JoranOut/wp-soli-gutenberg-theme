	<h2 class="wp-block-heading">Algemeen</h2>
	<!-- /wp:heading -->

	<!-- wp:paragraph -->
	<p>Het bestuur van Muziekvereniging Soli hecht veel waarde aan uw privacy en vindt het van groot belang dat de persoonsgegevens die door de vereniging worden verzameld en verwerkt, zo goed mogelijk worden beschermd. Muziekvereniging Soli is verplicht om zorgvuldig en veilig, proportioneel en vertrouwelijk om te gaan met het verzamelen, bewaren en beheren van persoonsgegevens van betrokkenen. Dit privacyreglement is van toepassing op alle verwerkingen van persoonsgegevens binnen Muziekvereniging Soli.</p>
	<!-- /wp:paragraph -->

	<!-- wp:heading -->
	<h2 class="wp-block-heading">Doel van het privacyreglement</h2>
	<!-- /wp:heading -->

	<!-- wp:paragraph -->
	<p>Dit privacyreglement is een verdieping van het privacybeleid dat is vastgesteld door het bestuur en beschrijft hoe de vereniging omgaat met de privacy van betrokkenen: welke persoonsgegevens worden verwerkt, met welke doeleinden, en hoe u uw rechten ten aanzien van uw persoonsgegevens kunt uitoefenen. Het reglement kan van tijd tot tijd worden aangepast, bijvoorbeeld om in lijn te blijven met geldende wet- en regelgeving of met de werkwijze van de vereniging.</p>
	<!-- /wp:paragraph -->

	<!-- wp:paragraph -->
	<p>Als u deze website bezoekt of zich inschrijft als lid, kan Muziekvereniging Soli gegevens van u verwerken: gegevens die u invult op een inschrijfformulier, een mail die u verstuurt via de website, enzovoort. Daarbij waarborgt en respecteert de vereniging uw privacy, onder andere door naleving van de Algemene Verordening Gegevensbescherming (AVG). Uw persoonsgegevens worden alleen gebruikt voor zover dat verenigbaar is met de doeleinden in dit reglement, ze worden beschermd, en u kunt uw rechten ten aanzien van uw gegevens uitoefenen.</p>
	<!-- /wp:paragraph -->

	<!-- wp:heading -->
	<h2 class="wp-block-heading">Doeleinden</h2>
	<!-- /wp:heading -->

	<!-- wp:paragraph -->
	<p>Muziekvereniging Soli verzamelt of gebruikt uw persoonsgegevens alleen voor de volgende doeleinden (artikel 5 AVG):</p>
	<!-- /wp:paragraph -->

	<!-- wp:list -->
	<ul class="wp-block-list">
		<!-- wp:list-item --><li>Activiteiten die, gelet op de doelstelling van de vereniging, gebruikelijk zijn — zoals inschrijving voor het lidmaatschap;</li><!-- /wp:list-item -->
		<!-- wp:list-item --><li>Betrokkenen voorzien van de juiste contactinformatie bij deelname aan activiteiten binnen de vereniging;</li><!-- /wp:list-item -->
		<!-- wp:list-item --><li>Het berekenen, vastleggen en innen van contributies, donaties, bijdragen van de Vrienden van Soli en sponsorbijdragen, en andere activiteiten van intern beheer;</li><!-- /wp:list-item -->
		<!-- wp:list-item --><li>Het verzenden van informatie over Soli-activiteiten en daarmee samenhangende PR-activiteiten, bijvoorbeeld nieuwsbrieven en bevestigingen bij inschrijving;</li><!-- /wp:list-item -->
		<!-- wp:list-item --><li>Het behandelen van geschillen en het laten uitoefenen van controle op de boekhouding.</li><!-- /wp:list-item -->
